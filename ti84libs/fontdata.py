HEIGHT = 8
SPACE_BELOW = 1          # one blank row between lines
FIRST, LAST = 32, 126


def glyph_rows(char: str) -> list[str]:
    """The glyph's 8 rows of "#" and ".", before the blank column that follows it."""
    if char in _DRAWN:
        return _DRAWN[char]
    if char in FONT_5X7:     # capitals, digits, and ?: the 5x7 glyphs the classic target draws
        return [row.replace("1", "#").replace("0", ".") for row in FONT_5X7[char]] + ["....."]
    raise KeyError(char)


@lru_cache(maxsize=1)
def font_bytes() -> bytes:
    """The font in FontLibC's format, as convfont writes it."""
    from ti84asm.convfont import Font, serialize_font

    widths, bitmaps = [], []
    for code in range(FIRST, LAST + 1):
        rows = [row + "." for row in glyph_rows(chr(code))]
        width = len(rows[0])
        assert len(rows) == HEIGHT and all(len(row) == width for row in rows), chr(code)
        widths.append(width)
        bitmaps.append(bytes(int(row.replace("#", "1").replace(".", "0").ljust(8, "0"), 2) for row in rows))
    return serialize_font(Font(HEIGHT, FIRST, widths, bitmaps, space_below=SPACE_BELOW,
                               cap_height=7, x_height=5, baseline_height=7))
