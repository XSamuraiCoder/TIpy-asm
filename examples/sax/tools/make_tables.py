# Letters printed in green above each key, and the 123-mode characters, by
# GetCSC scan code (keyboard.KEYS).
KEYS = {
    47: "a!", 39: "b@", 31: "c#", 46: "d&", 38: "e=", 30: "f<", 22: "g>", 14: "h^", 45: "i%",
    37: "j,", 29: "k(", 21: "l)", 13: "m/", 44: "n;", 36: "o7", 28: "p8", 20: "q9", 12: "r*",
    43: "s_", 35: "t4", 27: "u5", 19: "v6", 11: "w-", 42: "x:", 34: "y1", 26: "z2", 18: "'3",
    33: " 0", 25: "..", 17: "?-", 10: '"+', 23: ",$",
}

OSK = [
    ["1234567890", "qwertyuiop", "asdfghjkl'", "zxcvbnm,.?"],
    ["1234567890", "QWERTYUIOP", "ASDFGHJKL\"", "ZXCVBNM;:!"],
    ["!@#$%^&*()", "-_=+[]{}\\|", "~`<>/;:\"'?", ".,0123456@"],
]


def codes(text: str) -> list[int]:
    return [ord(ch) for ch in text]


def tuple_line(name: str, values: list[int]) -> str:
    rows = [", ".join(str(v) for v in values[i:i + 20]) for i in range(0, len(values), 20)]
    return f"{name} = (\n    " + ",\n    ".join(rows) + ",\n)\n"


def main() -> None:
    text, start, length = [], [], []
    out = ['"""Generated by tools/make_tables.py: SAX\'s text and keys as character codes. Do not edit."""\n']
    for index, (name, message) in enumerate(MESSAGES.items()):
        out.append(f"{name} = {index}\n")
        start.append(len(text))
        length.append(len(message))
        text.extend(codes(message))
    out.append("\n")
    out.append(tuple_line("MSG_TEXT", text))
    out.append(tuple_line("MSG_START", start))
    out.append(tuple_line("MSG_LEN", length))
    lower = [0] * 57
    number = [0] * 57
    for key, (low, num) in KEYS.items():
        lower[key], number[key] = ord(low), ord(num)
    out.append(tuple_line("KEY_LOWER", lower))
    out.append(tuple_line("KEY_NUMBER", number))
    out.append(tuple_line("OSK_CHARS", [ord(ch) for layer in OSK for row in layer for ch in row]))
    path = Path(__file__).resolve().parent.parent / "src" / "tables.py"
    path.write_text("".join(out), encoding="utf-8")
    print(f"Wrote {path}")


if __name__ == "__main__":
    main()
