# Assets.

def build_assets(config: ProjectConfig, force: bool = False) -> tuple[list[Path], list[Path]]:
    """Convert assets that are out of date; return (written, unchanged) outputs.

    Sprites built into the program, and pack indexes, go in generated modules;
    sprite packs share one AppVar.
    """
    written, unchanged = [], []
    for asset in config.assets:
        if not asset.source.is_file():
            raise CompileError(f"asset source not found: {asset.source}")
    for module in generate_asset_modules(config):
        written.append(module)
    packs: dict[str, list[Asset]] = {}
    for asset in config.assets:
        if asset.storage == "pack":
            packs.setdefault(asset.pack, []).append(asset)
            continue
        output = asset.output(config.bindir)
        if output is None:
            continue
        if not force and output.is_file() and output.stat().st_mtime >= asset.source.stat().st_mtime:
            unchanged.append(output)
            continue
        written.extend(_convert_asset(asset, output))
    for name, members in packs.items():
        output = config.bindir / f"{name}.8xv"
        newest = max(asset.source.stat().st_mtime for asset in members)
        if not force and output.is_file() and output.stat().st_mtime >= newest:
            unchanged.append(output)
            continue
        from .convimg import convert_sprite_pack
        written.append(convert_sprite_pack([asset.source for asset in members], output, name))
    return written, unchanged


def generate_asset_modules(config: ProjectConfig) -> list[Path]:
    """Write the modules for program and pack sprites; return the ones that changed.

    Program sprites become graphics.sprite() pixel constants, and pack sprites
    become their index in the pack, for sprite.load(PACK, index).
    """
    modules: dict[str, list[Asset]] = {}
    for asset in config.assets:
        if asset.storage in ("program", "pack"):
            modules.setdefault(asset.module, []).append(asset)
    changed = []
    for module, members in modules.items():
        path = config.main.parent / f"{module}.py"
        text = _asset_module_text(members)
        if path.is_file():
            current = path.read_text(encoding="utf-8")
            if current == text:
                continue
            if not current.startswith(GENERATED_HEADER):
                raise CompileError(f"{path} was not generated by tipy-asm; rename it, or set a different "
                                   f"module for its sprites in [[tool.tipy.assets]]")
        path.write_text(text, encoding="utf-8")
        changed.append(path)
    return changed


def _asset_module_text(members: list[Asset]) -> str:
    from .image import sprite_rows

    lines = [GENERATED_HEADER, "Every build rewrites it, so edit pyproject.toml and the images instead.", '"""', ""]
    indexes: dict[str, int] = {}
    for asset in members:
        if not asset.source.is_file():
            raise CompileError(f"asset source not found: {asset.source}")
        lines.append("")
        if asset.storage == "program":
            lines.append(f"# {asset.source.name}, built into the program: graphics.sprite({asset.name}, x, y)")
            lines.append(f"{asset.name} = (")
            lines.extend(sprite_rows(asset.source))
            lines.append(")")
        else:
            index = indexes.get(asset.pack, 0)
            indexes[asset.pack] = index + 1
            lines.append(f'# {asset.source.name}, sprite {index} of the {asset.pack} AppVar: '
                         f'sprite.load("{asset.pack}", {asset.name})')
            lines.append(f"{asset.name} = {index}")
    return "\n".join(lines) + "\n"


def _convert_asset(asset: Asset, output: Path) -> list[Path]:
    if asset.kind == "sprite":
        from .convimg import convert_sprite
        return [convert_sprite(asset.source, output, asset.name)]
    if asset.kind == "image":
        from .convimg import convert
        return convert(asset.source, output, "8xv", asset.name, asset.mode)
    if asset.kind == "font":
        from .convfont import font_appvar
        return [font_appvar(asset.source, output, asset.name)]
    from .convbin import MAX_VAR_SIZE, TYPE_APPVAR, ti_file
    data = asset.source.read_bytes()
    if len(data) > MAX_VAR_SIZE:
        raise CompileError(f"{asset.source} is {len(data)} bytes, too large for one AppVar (max {MAX_VAR_SIZE})")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(ti_file(TYPE_APPVAR, asset.name, data, archived=True))
    return [output]


