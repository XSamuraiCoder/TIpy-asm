#!/usr/bin/env python3
"""Compile a small, typed Python subset to TI-83+/TI-84 Z80 assembly."""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

from .errors import CompileError

# ti84libs is a sibling package. Make that sibling visible when Python starts
# the installed console-script launcher, whose initial sys.path may omit cwd.
_PACKAGE_ROOT = str(Path(__file__).resolve().parent.parent)
if _PACKAGE_ROOT not in sys.path:
    sys.path.insert(0, _PACKAGE_ROOT)

from ti84libs import emit_attribute, emit_call, emit_expression


class Compiler:
    def __init__(self, program: str, target: str = "classic"):
        self.program = re.sub(r"[^A-Za-z0-9_]", "_", program.upper())[:8] or "PYPROG"
        self.target = target
        self.lines: list[str] = []
        self.data: list[str] = []
        self.variables: dict[str, str] = {}
        self.modules: dict[str, str] = {}
        self.label_id = 0

    def emit(self, line: str = "") -> None:
        self.lines.append(line)

    def label(self, stem: str) -> str:
        self.label_id += 1
        return f"_{stem}_{self.label_id}"

    def directive(self, kind: str) -> str:
        return ("." if self.target == "classic" else "") + kind

    def byte_literal(self, value: int) -> str:
        return f"0{value:02X}h" if self.target == "classic" else f"${value:02X}"

    def variable(self, name: str) -> str:
        if not name.isidentifier():
            raise CompileError(f"invalid variable name: {name}")
        if name not in self.variables:
            self.variables[name] = f"var_{len(self.variables)}"
        return self.variables[name]

    def compile(self, source: str) -> str:
        try:
            tree = ast.parse(source)
        except SyntaxError as exc:
            raise CompileError(f"line {exc.lineno}: {exc.msg}") from exc
        self.emit(f"; Generated by TIpy-asm for {self.program}")
        if self.target == "classic":
            self.emit("; Target: TI-83+/TI-84 Plus Z80, TASM-style syntax")
            self.emit('#include "ti83plus.inc"')
            self.emit(".org userMem-2")
            self.emit(".db t2ByteTok, tAsmCmp")
            self.emit(".dw start")
        else:
            self.emit("; Target: TI-84 Plus CE eZ80, fasmg TI executable format")
            self.emit("include 'include/ez80.inc'")
            self.emit("include 'include/tiformat.inc'")
            self.emit("include 'include/ti84pceg.inc'")
            self.emit(f"format ti executable '{self.program}'")
        self.emit("start:")
        for stmt in tree.body:
            self.statement(stmt)
        if self.target == "ce":
            self.emit("program_exit:")
            self.emit("    call ti.ClrScrn")
            self.emit("    ld a,ti.lcdBpp16")
            self.emit("    ld (ti.mpLcdCtrl),a")
            self.emit("    call ti.DrawStatusBar")
            self.emit("    ei")
            self.emit("    ret")
        else:
            self.emit("    ret")
        if self.data:
            self.emit("\n; String literals")
            self.lines.extend(self.data)
        if self.variables:
            self.emit("\n; 16-bit signed integer variables")
            for label in self.variables.values():
                if self.target == "ce":
                    # CE code runs in ADL mode: LD (nn),HL accesses three bytes.
                    self.emit(f"{label}: db 0,0,0")
                else:
                    self.emit(f"{label}: .dw 0")
        return "\n".join(self.lines) + "\n"

    def statement(self, node: ast.stmt) -> None:
        if isinstance(node, ast.Import):
            for item in node.names:
                if item.name not in ("ti84.graphics", "ti84.storage", "ti84.keyboard", "ti84.math") or not item.asname:
                    raise CompileError("library imports use ti84.graphics, ti84.storage, ti84.keyboard, or ti84.math with an alias")
                self.modules[item.asname] = item.name
        elif isinstance(node, ast.ImportFrom) and node.module == "ti84":
            for item in node.names:
                if item.name not in ("graphics", "storage", "keyboard", "math"):
                    raise CompileError(f"unknown ti84 library: {item.name}")
                self.modules[item.asname or item.name] = f"ti84.{item.name}"
        elif isinstance(node, ast.ImportFrom):
            raise CompileError(f"line {node.lineno}: unsupported library import from {node.module}")
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            target = self.variable(node.targets[0].id)
            self.expression(node.value)
            self.emit(f"    ld ({target}),hl")
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.value:
            target = self.variable(node.target.id)
            self.expression(node.value)
            self.emit(f"    ld ({target}),hl")
        elif isinstance(node, ast.AugAssign) and isinstance(node.target, ast.Name):
            target = self.variable(node.target.id)
            constant = self.constant_integer(node.value)
            if constant is not None and isinstance(node.op, (ast.Add, ast.Sub)):
                self.emit(f"    ld hl,({target})")
                self.emit(f"    ld de,{constant & 0xFFFF}")
                self.binary(node.op)
            else:
                self.emit(f"    ld hl,({target})")
                self.emit("    push hl")
                self.expression(node.value)
                self.emit("    ex de,hl")
                self.emit("    pop hl")
                self.binary(node.op)
            self.emit(f"    ld ({target}),hl")
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            self.call(node.value)
        elif isinstance(node, ast.If):
            otherwise, end = self.label("else"), self.label("endif")
            self.condition_false(node.test, otherwise)
            for child in node.body:
                self.statement(child)
            if node.orelse:
                self.emit(f"    jp {end}")
            self.emit(otherwise + ":")
            for child in node.orelse:
                self.statement(child)
            if node.orelse:
                self.emit(end + ":")
        elif isinstance(node, ast.While):
            top, done = self.label("while"), self.label("wend")
            self.emit(top + ":")
            self.condition_false(node.test, done)
            for child in node.body:
                self.statement(child)
            self.emit(f"    jp {top}")
            self.emit(done + ":")
        elif isinstance(node, ast.Pass):
            return
        else:
            raise CompileError(f"line {getattr(node, 'lineno', '?')}: unsupported statement {type(node).__name__}")

    def call(self, node: ast.Call) -> None:
        if isinstance(node.func, ast.Name) and node.func.id == "print":
            if len(node.args) != 1 or node.keywords:
                raise CompileError("print() accepts one string literal")
            arg = node.args[0]
            if not isinstance(arg, ast.Constant) or not isinstance(arg.value, str):
                raise CompileError("print() currently accepts one string literal")
            label = self.label("str")
            encoded = arg.value.encode("ascii", errors="strict") + b"\0"
            self.data.append(label + ": " + self.directive("db") + " " + ",".join(self.byte_literal(b) for b in encoded))
            self.emit(f"    ld hl,{label}")
            if self.target == "classic":
                self.emit("    bcall(_PutS)")
                self.emit("    bcall(_NewLine)")
            else:
                self.emit("    call ti.PutS")
                self.emit("    call ti.NewLine")
            return

        emit_call(self, node)

    def expression(self, node: ast.expr) -> None:
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name):
            emit_expression(self, node)
        elif isinstance(node, ast.Attribute):
            emit_attribute(self, node)
        elif isinstance(node, (ast.Constant, ast.UnaryOp, ast.BinOp)) and self.constant_integer(node) is not None:
            value = self.constant_integer(node)
            self.emit(f"    ld hl,{value & 0xFFFF}")
        elif isinstance(node, ast.Constant) and isinstance(node.value, int) and not isinstance(node.value, bool):
            if not -32768 <= node.value <= 32767:
                raise CompileError("integer constants must fit signed 16-bit range")
            self.emit(f"    ld hl,{node.value & 0xffff}")
        elif isinstance(node, ast.Name):
            self.emit(f"    ld hl,({self.variable(node.id)})")
        elif isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            self.expression(node.operand)
            self.emit("    xor a")
            self.emit("    sub l")
            self.emit("    ld l,a")
            self.emit("    sbc a,a")
            self.emit("    sub h")
            self.emit("    ld h,a")
        elif isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub)):
            if isinstance(node.right, ast.Constant) and isinstance(node.right.value, int) and not isinstance(node.right.value, bool):
                self.expression(node.left)
                self.emit(f"    ld de,{node.right.value & 0xFFFF}")
                self.binary(node.op)
            elif isinstance(node.op, ast.Add) and isinstance(node.left, ast.Constant) and isinstance(node.left.value, int) and not isinstance(node.left.value, bool):
                self.expression(node.right)
                self.emit(f"    ld de,{node.left.value & 0xFFFF}")
                self.binary(node.op)
            else:
                self.expression(node.left)
                self.emit("    push hl")
                self.expression(node.right)
                self.emit("    ex de,hl")
                self.emit("    pop hl")
                self.binary(node.op)
        else:
            raise CompileError(f"unsupported expression: {ast.dump(node, include_attributes=False)}")

    @staticmethod
    def constant_integer(node: ast.expr) -> int | None:
        """Evaluate the supported integer-only expression subset at compile time."""
        if isinstance(node, ast.Constant) and isinstance(node.value, int) and not isinstance(node.value, bool):
            return node.value if -32768 <= node.value <= 32767 else None
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            value = Compiler.constant_integer(node.operand)
            return -value if value is not None else None
        if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub)):
            left = Compiler.constant_integer(node.left)
            right = Compiler.constant_integer(node.right)
            if left is None or right is None:
                return None
            return left + right if isinstance(node.op, ast.Add) else left - right
        return None

    def binary(self, op: ast.operator) -> None:
        if isinstance(op, ast.Add):
            self.emit("    add hl,de")
        elif isinstance(op, ast.Sub):
            self.emit("    or a")
            self.emit("    sbc hl,de")
        else:
            raise CompileError("only integer + and - are supported")

    def condition_false(self, node: ast.expr, false_label: str) -> None:
        if isinstance(node, ast.Compare) and len(node.ops) == 1 and len(node.comparators) == 1:
            op = node.ops[0]
            self.expression(node.left)
            right = self.constant_integer(node.comparators[0])
            if right is not None:
                self.emit(f"    ld de,{right & 0xFFFF}")
            else:
                self.emit("    push hl")
                self.expression(node.comparators[0])
                self.emit("    ex de,hl")
                self.emit("    pop hl")
            self.emit("    or a")
            self.emit("    sbc hl,de")
            if isinstance(op, ast.Eq):
                self.emit(f"    jp nz,{false_label}")
            elif isinstance(op, ast.NotEq):
                self.emit(f"    jp z,{false_label}")
            elif isinstance(op, ast.Lt):
                self.emit(f"    jp nc,{false_label}")
            elif isinstance(op, ast.Gt):
                self.emit(f"    jp c,{false_label}")
                self.emit(f"    jp z,{false_label}")
            else:
                raise CompileError("conditions support ==, !=, <, and >")
        else:
            raise CompileError("if/while conditions must be a single integer comparison")


