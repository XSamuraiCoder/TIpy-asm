"""Image-to-TIpy source conversion helpers."""

from __future__ import annotations

from pathlib import Path

from .errors import CompileError


def _rgb565(red: int, green: int, blue: int) -> int:
    return ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)


def convert_image(image_path: Path, output_path: Path, x: int = 0, y: int = 0,
                  alpha_threshold: int = 128, fit: str | None = None) -> None:
    """Write a Python-subset program drawing an image as a TIpy sprite."""
    try:
        from PIL import Image
    except ImportError as exc:
        raise CompileError("image conversion needs Pillow; install it with: python -m pip install 'tipy-asm[images]'") from exc

    if not 0 <= alpha_threshold <= 255:
        raise CompileError("alpha threshold must be between 0 and 255")
    try:
        with Image.open(image_path) as source:
            image = source.convert("RGBA")
    except (OSError, ValueError) as exc:
        raise CompileError(f"cannot read image {image_path}: {exc}") from exc

    width, height = image.size
    if not width or not height:
        raise CompileError("image must have nonzero width and height")
    if fit is not None:
        limits = {"classic": (96, 64), "ce": (320, 240)}
        if fit not in limits:
            raise CompileError('image fit must be "classic" or "ce"')
        image.thumbnail(limits[fit], Image.Resampling.NEAREST)
        width, height = image.size
    rows: list[str] = []
    pixels = image.load()
    for row in range(height):
        values = []
        for col in range(width):
            red, green, blue, alpha = pixels[col, row]
            values.append("None" if alpha < alpha_threshold else f"0x{_rgb565(red, green, blue):04X}")
        rows.append("    (" + ", ".join(values) + ",),")

    output = [
        '"""Generated by ti84py convert-image. Edit x/y or the sprite pixels as needed."""',
        "import ti84.graphics as graphics",
        "",
        "graphics.sprite((",
        *rows,
        f"), {x}, {y})",
        "",
    ]
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(output), encoding="ascii")
